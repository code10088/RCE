"""Build an offline evidence bundle and optional Ghidra/IDA annotation scripts."""
import argparse
import json
import re
from collections import Counter
from pathlib import Path


def load(path):
    text = Path(path).read_text(encoding="utf-8-sig", errors="replace").strip()
    if not text:
        return []
    try:
        value = json.loads(text)
        return value if isinstance(value, list) else [value]
    except json.JSONDecodeError:
        return [json.loads(line) for line in text.splitlines() if line.strip()]


def methods(value):
    out = []
    def walk(node):
        if isinstance(node, dict):
            for cls in node.get("classes", []) if isinstance(node.get("classes"), list) else []:
                full = "%s.%s" % (cls.get("namespace", ""), cls.get("name", ""))
                for method in cls.get("methods", []):
                    out.append({"class": full, "name": method.get("name", ""),
                                "rva": method.get("rva"), "params": method.get("params", []),
                                "ret": method.get("ret", "")})
            for item in node.values():
                if isinstance(item, (dict, list)):
                    walk(item)
        elif isinstance(node, list):
            for item in node:
                walk(item)
    walk(value)
    return out


def safe_name(item):
    value = "%s::%s" % (item["class"], item["name"])
    return re.sub(r"[^A-Za-z0-9_$:.]", "_", value)[:180]


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("classes", type=Path)
    parser.add_argument("--calibration", type=Path)
    parser.add_argument("--stalker", action="append", type=Path, default=[])
    parser.add_argument("--image-base", default="0x0",
                        help="static image base used by the loaded Ghidra binary")
    parser.add_argument("--out", required=True, type=Path)
    args = parser.parse_args(argv)
    items = methods(load(args.classes))
    addresses = {}
    if args.calibration:
        report = json.loads(args.calibration.read_text(encoding="utf-8-sig"))
        addresses = {str(x.get("rva")): x.get("runtime_address") for x in report.get("methods", [])}
    counts = Counter()
    for path in args.stalker:
        for row in load(path):
            address = row.get("rva") or row.get("addr") or row.get("pc")
            if address:
                counts[str(address)] += 1
    annotations = []
    image_base = int(str(args.image_base), 0)
    for item in items:
        rva = str(item.get("rva")) if item.get("rva") is not None else ""
        annotations.append({**item, "name": safe_name(item),
                            "static_address": hex(image_base + int(rva, 0)) if rva else None,
                            "runtime_address": addresses.get(rva),
                            "trace_hits": counts.get(rva, 0)})
    args.out.mkdir(parents=True, exist_ok=True)
    bundle = {"source": str(args.classes.resolve()), "annotations": annotations,
              "trace_hit_addresses": counts}
    (args.out / "backfill.json").write_text(json.dumps(bundle, indent=2, ensure_ascii=False, default=dict) + "\n",
                                            encoding="utf-8")
    rows = [x for x in annotations if x.get("rva") not in (None, "", "0", "0x0")]
    ghidra = ["// Generated by static/backfill.py", "from ghidra.program.model.symbol import SourceType", "", "def run():"]
    ghidra.append("    tx = currentProgram.startTransaction('IL2CPP evidence backfill')")
    ghidra.append("    try:")
    for row in rows:
        addr = row["static_address"]
        ghidra.append("        f = getFunctionAt(toAddr(%s)); name = %r" % (addr, row["name"]))
        ghidra.append("        if f: f.setName(name, SourceType.USER_DEFINED); f.setComment('%s')" %
                      ("trace_hits=" + str(row["trace_hits"])))
    ghidra += ["    finally:", "        currentProgram.endTransaction(tx, True)", "", "run()", ""]
    (args.out / "backfill_ghidra.py").write_text("\n".join(ghidra), encoding="utf-8")
    ida = ["# Generated by static/backfill.py", "import idaapi, ida_name", ""]
    for row in rows:
        ida.append("ea=idaapi.get_imagebase()+int(%r, 0); ida_name.set_name(ea, %r, ida_name.SN_FORCE); idaapi.set_cmt(ea, %r, 0)" %
                   (str(row["rva"]), row["name"], "trace_hits=" + str(row["trace_hits"])))
    (args.out / "backfill_ida.py").write_text("\n".join(ida) + "\n", encoding="utf-8")
    print("Wrote %d annotations to %s" % (len(annotations), args.out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
